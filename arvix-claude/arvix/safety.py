"""Детектор safety-контура (02-MECHANICS §6, шаг 1.4 плана).

Список маркеров — код, а не просьба к модели. Ложное срабатывание стоит дёшево
(ментор выключается до ручного /mentor on), пропуск — дорого. П1: безопасность
выше дисциплины.
"""

from __future__ import annotations

import re

MARKERS = [
    r"не\s+хочу\s+(больше\s+)?жить", r"хочу\s+умереть", r"покончить\s+с\s+собой", r"покончу\s+с\s+собой",
    r"суицид", r"самоубийств", r"убить\s+себя", r"убью\s+себя", r"нет\s+смысла\s+жить",
    r"не\s+вижу\s+смысла\s+жить", r"лучше\s+бы\s+меня\s+не\s+было", r"режу\s+себя", r"порезать\s+себя",
    r"самоповрежд", r"вскрыть\s+вены", r"исчезнуть\s+навсегда", r"всем\s+будет\s+лучше\s+без\s+меня",
]
_PATTERN = re.compile("|".join(MARKERS), re.IGNORECASE)


def detect(text: str) -> bool:
    return bool(_PATTERN.search(text or ""))
